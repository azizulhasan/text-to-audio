// Read the .pot file
const potContent = fs.readFileSync(path.join(__dirname, '../languages/text-to-audio.pot'), 'utf8');

// Replace header for Spanish
let poContent = potContent
  .replace('# Copyright (C) 2026 AtlasAiDev', '# Spanish (Spain) translation for Text To Speech TTS Accessibility')
  .replace('"Last-Translator: FULL NAME <EMAIL@ADDRESS>\\n"', '"Last-Translator: AtlasAiDev <support@atlasaidev.com>\\n"')
  .replace('"Language-Team: LANGUAGE <LL@li.org>\\n"', '"Language-Team: Spanish (Spain) <es@li.org>\\n"')
  .replace('"PO-Revision-Date: YEAR-MO-DA HO:MI+ZONE\\n"', '"PO-Revision-Date: 2026-03-10 12:00+0000\\n"');

// Add Language header after Content-Transfer-Encoding
poContent = poContent.replace(
  '"Content-Transfer-Encoding: 8bit\\n"',
  '"Content-Transfer-Encoding: 8bit\\n"\n"Language: es_ES\\n"\n"Plural-Forms: nplurals=2; plural=(n != 1);\\n"'
);

// Process line by line for accurate matching
const lines = poContent.split('\n');
const outputLines = [];
let currentMsgid = '';
let collectingMsgid = false;
let translated = 0;
let total = 0;

for (let i = 0; i < lines.length; i++) {
  const line = lines[i];

  if (line.startsWith('msgid "') && !line.startsWith('msgid ""')) {
    currentMsgid = line.replace(/^msgid "/, '').replace(/"$/, '');
    collectingMsgid = false;
    outputLines.push(line);
    continue;
  }

  if (collectingMsgid && line.startsWith('"')) {
    currentMsgid += line.replace(/^"/, '').replace(/"$/, '');
    outputLines.push(line);
    continue;
  }

  if (line === 'msgid ""') {
    currentMsgid = '';
    collectingMsgid = true;
    outputLines.push(line);
    continue;
  }

  if (line === 'msgstr ""' && currentMsgid) {
    total++;
    const translation = translations[currentMsgid];
    if (translation !== undefined) {
      outputLines.push(`msgstr "${translation}"`);
      translated++;
    } else {
      outputLines.push(line);
    }
    currentMsgid = '';
    collectingMsgid = false;
    continue;
  }

  collectingMsgid = false;
  outputLines.push(line);
}

const outputPath = path.join(__dirname, '../languages/text-to-audio-es_ES.po');
fs.writeFileSync(outputPath, outputLines.join('\n'), 'utf8');

console.log(`Translated: ${translated}/${total} strings`);
console.log(`Output: ${outputPath}`);
